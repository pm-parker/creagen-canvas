def seed_prompts_if_empty(db: Session) -> int:
    """prompts 表为空时导入内置库；返回导入条数。幂等：非空不动作。"""
    count = db.query(Prompt).count()
    if count > 0:
        return 0
    now_items = []
    for item in SEED_PROMPTS:
        now_items.append(
            Prompt(
                title=item["title"],
                content=item["content"],
                category=item["category"],
                source="builtin",
            )
        )
    db.add_all(now_items)
    db.commit()
    logger.info("Seeded %d builtin prompts", len(now_items))
    return len(now_items)
